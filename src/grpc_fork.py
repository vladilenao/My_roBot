"""Настройки gRPC до его загрузки: обработчики fork() и поиск адреса брокера.

``run.py`` импортирует модуль первым, до загрузки gRPC; значения, заданные
снаружи, не меняются. Процессы контуров получают их и по наследству окружения
ядра, и собственным импортом в ``run.py --contour``.

Обработчики fork() (add-contour-process). Ядро многопоточно и держит вызовы
gRPC брокера, а ``subprocess`` на macOS запускает процесс контура через fork()
и exec. Поддержка fork в gRPC при этом печатает в консоль ядра сотни строк
``fork_posix.cc`` / ``ev_poll_posix.cc`` и ничего не даёт: дочерний процесс
сразу выполняет exec и gRPC родителя не использует.

Поиск адреса (fix-grpc-system-dns). Резолвер gRPC по умолчанию (c-ares) сам
опрашивает DNS-серверы из настроек сети. 25.11.2026 первый из них не отвечал,
и контуры не стартовали с «Timeout while contacting DNS servers», хотя система
находила адрес брокера. Системный поиск (``native``, ``getaddrinfo``) работает
как остальные программы.
"""

import os

os.environ.setdefault("GRPC_ENABLE_FORK_SUPPORT", "0")
os.environ.setdefault("GRPC_DNS_RESOLVER", "native")
